class _L298nJumperInfoDialog(QDialog):
    """Level 3 read-only modal: documents the L298N jumpers (5V_EN on one
    hand, ENA/ENB on the other). 2 columns of text + photo zone at the
    top.

    The ENA/ENB text is automatically adapted according to what the code
    does (PWM on ENA+ENB / ENA only / ENB only / none). Today the
    detector's S1-S4 cascade always requires `analogWrite()` to classify
    a motor pin as PWM -- so the "no PWM" case is not reachable. The 4
    versions are nonetheless ready if the detector later learns to
    recognize the digital-only patterns.
    """
    def __init__(self, parent, *, ref: str, l298n_component):
        super().__init__(parent)
        lang = lang_manager.lang
        self.setWindowTitle(_t("l298n_jumper_title", lang).format(ref=ref))
        self.setModal(True)
        self.setMinimumSize(980, 680)

        root = QVBoxLayout(self)
        root.setContentsMargins(20, 18, 20, 14)
        root.setSpacing(12)

        # Photo zone: annotated SVG of the L298N jumpers. Rendered via
        # QSvgRenderer -> QPixmap to preserve the proportions (the native
        # QSvgWidget stretches the rendering to the allocated zone).
        # Fallback placeholder if the file is absent.
        photo_path = (Path(__file__).resolve().parents[2]
                      / "assets" / "wiring" / "docs" / "l298n_jumpers.svg")
        if photo_path.exists():
            renderer = QSvgRenderer(str(photo_path))
            default = renderer.defaultSize()
            target_h = 220
            aspect = (default.width() / default.height()
                      if default.height() else 1.0)
            target_w = max(1, int(round(target_h * aspect)))
            pixmap = QPixmap(target_w, target_h)
            pixmap.fill(Qt.GlobalColor.transparent)
            painter = QPainter(pixmap)
            painter.setRenderHint(QPainter.RenderHint.Antialiasing)
            painter.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
            renderer.render(painter)
            painter.end()
            photo = QLabel()
            photo.setPixmap(pixmap)
            photo.setAlignment(Qt.AlignmentFlag.AlignCenter)
        else:
            photo = QLabel(_t("l298n_photo_missing", lang))
            photo.setAlignment(Qt.AlignmentFlag.AlignCenter)
            photo.setMinimumHeight(140)
            # Themed by `_style_choice_dialog` (called at the end of this
            # constructor) via this object name -- see ASSET_PLACEHOLDER_NAME.
            photo.setObjectName(ASSET_PLACEHOLDER_NAME)
        root.addWidget(photo)

        # 2 columns: 5V_EN on the left, ENA/ENB on the right.
        cols = QHBoxLayout()
        cols.setSpacing(16)
        cols.addLayout(self._build_5v_en_column(), 1)
        cols.addLayout(self._build_ena_enb_column(l298n_component), 1)
        root.addLayout(cols, 1)

        btns = QDialogButtonBox(QDialogButtonBox.StandardButton.Ok)
        localize_button_box(btns, ok=lang_manager.current.btn_understood)
        btns.accepted.connect(self.accept)
        root.addWidget(btns)
        _style_choice_dialog(self, btns)

    def _build_5v_en_column(self) -> QVBoxLayout:
        lang = lang_manager.lang
        col = QVBoxLayout()
        col.setSpacing(6)
        col.addWidget(QLabel(_t("l298n_5v_en_heading", lang)))
        body = QLabel(_t("l298n_5v_en_body", lang))
        body.setWordWrap(True)
        body.setTextFormat(Qt.TextFormat.RichText)
        body.setAlignment(Qt.AlignmentFlag.AlignTop)
        col.addWidget(body, 1)
        return col

    def _build_ena_enb_column(self, comp) -> QVBoxLayout:
        lang = lang_manager.lang
        col = QVBoxLayout()
        col.setSpacing(6)
        col.addWidget(QLabel(_t("l298n_ena_enb_heading", lang)))
        intro = _t("l298n_ena_enb_intro", lang)
        a_pwm, b_pwm = self._detect_pwm_sides(comp)
        prescription = self._ena_enb_prescription(a_pwm, b_pwm)
        body = QLabel(intro + prescription)
        body.setWordWrap(True)
        body.setTextFormat(Qt.TextFormat.RichText)
        body.setAlignment(Qt.AlignmentFlag.AlignTop)
        col.addWidget(body, 1)
        return col

    @staticmethod
    def _detect_pwm_sides(comp) -> tuple[bool, bool]:
        """Returns (a_pwm, b_pwm). True when the EN* pin is on an Arduino
        signal net (not '5V'/'GND'/'BAT_*'). False if the pin is absent
        (unused side) or pinned at +5V (degenerate case of the inference
        when the detector found no aux_dir_pins)."""
        def _is_pwm(side: str) -> bool:
            pin = comp.pin("ENA" if side == "A" else "ENB")
            if pin is None:
                return False
            net = pin.net or ""
            return (net not in ("5V", "GND")
                    and not net.startswith("BAT_"))
        return _is_pwm("A"), _is_pwm("B")

    @staticmethod
    def _ena_enb_prescription(a_pwm: bool, b_pwm: bool) -> str:
        """Prescription text adapted to the detected case. 4 possible
        variants. Today (the S1-S4 cascade requires analogWrite), only A
        and B are really reachable, but C/D are ready if the detector
        evolves."""
        lang = lang_manager.lang
        if a_pwm and b_pwm:
            # Version A: PWM on both motors.
            return _t("l298n_prescription_both_pwm", lang)
        if a_pwm and not b_pwm:
            # Version B: PWM on motor A only.
            return _t("l298n_prescription_a_pwm_only", lang)
        if b_pwm and not a_pwm:
            # Version C: PWM on motor B only.
            return _t("l298n_prescription_b_pwm_only", lang)
        # Version D: no PWM detected.
        return _t("l298n_prescription_no_pwm", lang)


class _L293dModuleJumperInfoDialog(QDialog):
    """Level 3 read-only modal: documents the L293D module's ENA/ENB
    jumpers.

    Unlike the L298N, the L293D module does NOT have an internal 5V
    regulator (so no 5V_EN jumper): the 2 supplies (logic VCC1 + motor
    VCC2) are brought in separately on the input. The only subtlety that
    warrants a warning is the presence (on some variants) of the ENA/ENB
    jumpers that short the enable to +5V, preventing PWM.

    Single-column modal (vs 2 columns for L298N). No photo zone (the
    annotated SVG asset does not exist, fairly rare module).
    """
    def __init__(self, parent, *, ref: str, l293d_component):
        super().__init__(parent)
        lang = lang_manager.lang
        self.setWindowTitle(_t("l293d_module_title", lang).format(ref=ref))
        self.setModal(True)
        self.setMinimumSize(560, 480)

        root = QVBoxLayout(self)
        root.setContentsMargins(20, 18, 20, 14)
        root.setSpacing(12)

        root.addLayout(self._build_ena_enb_column(l293d_component), 1)

        btns = QDialogButtonBox(QDialogButtonBox.StandardButton.Ok)
        localize_button_box(btns, ok=lang_manager.current.btn_understood)
        btns.accepted.connect(self.accept)
        root.addWidget(btns)
        _style_choice_dialog(self, btns)

    def _build_ena_enb_column(self, comp) -> QVBoxLayout:
        lang = lang_manager.lang
        col = QVBoxLayout()
        col.setSpacing(6)
        col.addWidget(QLabel(_t("l293d_module_ena_enb_heading", lang)))
        intro = _t("l293d_module_ena_enb_intro", lang)
        a_pwm, b_pwm = self._detect_pwm_sides(comp)
        prescription = self._ena_enb_prescription(a_pwm, b_pwm)
        body = QLabel(intro + prescription)
        body.setWordWrap(True)
        body.setTextFormat(Qt.TextFormat.RichText)
        body.setAlignment(Qt.AlignmentFlag.AlignTop)
        col.addWidget(body, 1)
        return col

    @staticmethod
    def _detect_pwm_sides(comp) -> tuple[bool, bool]:
        """Same pins (ENA/ENB) as the L298N so same logic. Cf
        `_L298nJumperInfoDialog._detect_pwm_sides` for the rationale."""
        def _is_pwm(side: str) -> bool:
            pin = comp.pin("ENA" if side == "A" else "ENB")
            if pin is None:
                return False
            net = pin.net or ""
            return (net not in ("5V", "GND")
                    and not net.startswith("BAT_"))
        return _is_pwm("A"), _is_pwm("B")

    @staticmethod
    def _ena_enb_prescription(a_pwm: bool, b_pwm: bool) -> str:
        """Same 4 versions as L298N. Cf
        `_L298nJumperInfoDialog._ena_enb_prescription`."""
        lang = lang_manager.lang
        if a_pwm and b_pwm:
            return _t("l293d_module_prescription_both_pwm", lang)
        if a_pwm and not b_pwm:
            return _t("l293d_module_prescription_a_pwm_only", lang)
        if b_pwm and not a_pwm:
            return _t("l293d_module_prescription_b_pwm_only", lang)
        return _t("l293d_module_prescription_no_pwm", lang)


class _A4988VrefInfoDialog(QDialog):
    """Level 3 read-only modal: documents the A4988's VREF potentiometer.

    VREF sets the maximum current sent to the motor via the formula
    `I_max = VREF / (8 x Rs)` where Rs is the sense resistance soldered
    on the board (varies by variant: 0.05 / 0.1 / 0.2 Ohm).

    The adjustment is 100% physical (screwdriver potentiometer +
    multimeter): impossible to detect or generate in equivalent wiring
    -- hence the read-only info modal rather than a Level 3 gear action.

    Single-column modal with an annotated photo
    (`assets/wiring/docs/a4988_vref.svg` -- potentiometer boxed in blue
    on the official Pololu SVG via Fritzing).
    """
    def __init__(self, parent, *, ref: str):
        super().__init__(parent)
        lang = lang_manager.lang
        self.setWindowTitle(_t("a4988_vref_title", lang).format(ref=ref))
        self.setModal(True)
        self.setMinimumSize(620, 720)

        root = QVBoxLayout(self)
        root.setContentsMargins(20, 18, 20, 14)
        root.setSpacing(12)

        # Annotated photo: Pololu A4988 SVG with the potentiometer boxed
        # in pure blue. Pattern identical to `_L298nJumperInfoDialog`.
        photo_path = (Path(__file__).resolve().parents[2]
                      / "assets" / "wiring" / "docs" / "a4988_vref.svg")
        if photo_path.exists():
            renderer = QSvgRenderer(str(photo_path))
            default = renderer.defaultSize()
            target_h = 240
            aspect = (default.width() / default.height()
                      if default.height() else 1.0)
            target_w = max(1, int(round(target_h * aspect)))
            pixmap = QPixmap(target_w, target_h)
            pixmap.fill(Qt.GlobalColor.transparent)
            painter = QPainter(pixmap)
            painter.setRenderHint(QPainter.RenderHint.Antialiasing)
            painter.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
            renderer.render(painter)
            painter.end()
            photo = QLabel()
            photo.setPixmap(pixmap)
            photo.setAlignment(Qt.AlignmentFlag.AlignCenter)
        else:
            photo = QLabel(_t("a4988_vref_photo_missing", lang))
            photo.setAlignment(Qt.AlignmentFlag.AlignCenter)
            photo.setMinimumHeight(140)
            # Themed by `_style_choice_dialog` (called at the end of this
            # constructor) via this object name -- see ASSET_PLACEHOLDER_NAME.
            photo.setObjectName(ASSET_PLACEHOLDER_NAME)
        root.addWidget(photo)

        root.addLayout(self._build_vref_column(), 1)

        btns = QDialogButtonBox(QDialogButtonBox.StandardButton.Ok)
        localize_button_box(btns, ok=lang_manager.current.btn_understood)
        btns.accepted.connect(self.accept)
        root.addWidget(btns)
        _style_choice_dialog(self, btns)

    def _build_vref_column(self) -> QVBoxLayout:
        lang = lang_manager.lang
        col = QVBoxLayout()
        col.setSpacing(6)
        col.addWidget(QLabel(_t("a4988_vref_heading", lang)))
        body = QLabel(_t("a4988_vref_body", lang))
        body.setWordWrap(True)
        body.setTextFormat(Qt.TextFormat.RichText)
        body.setAlignment(Qt.AlignmentFlag.AlignTop)
        col.addWidget(body, 1)
        return col


