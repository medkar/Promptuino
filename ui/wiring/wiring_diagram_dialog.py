    def _on_regenerate_clicked(self):
        """'Edit choices' button: forces the ambiguity modal for ALL the
        sketch's ambiguous components (bypassing the saved resolutions).
        Lets the user correct a previous bad choice. Cancelling the modal
        = we keep the current diagram and the saved resolutions
        unchanged."""
        if self._resolve_fn is None:
            self._regenerate()   # fallback simple re-render
            return
        new_netlist = self._resolve_fn(
            self._code, self._board_id,
            self._prompt, self._context, self._prompts_by_fn,
            force_remodal=True,
        )
        if new_netlist is None:
            return   # modal cancelled: we keep the old diagram
        self._netlist = new_netlist
        self._regenerate()

    def _resolution_key(self, component) -> tuple[str, str]:
        """Key for the persistent resolutions map: (fn_id, pin_net).

        fn_id allows scoping per feature (regenerating fn-1 must not
        erase the choices of fn-2). pin_net distinguishes several
        ambiguous components in the same feature (e.g. 2 OUTPUT).
        """
        sig = (component.pin("A") or component.pin("SIG") or
               (component.pins[0] if component.pins else None))
        net = sig.net if sig else "?"
        return (component.fn_id or "", net)

