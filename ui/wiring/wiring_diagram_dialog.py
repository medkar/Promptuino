    def _render_png_image(self, scale: float = 2.0) -> QImage:
        """Rasterizes the current SVG to a QImage, with the mandatory watermark.

        The watermark (logo + URL) is placed UNDER the board. If the board
        touches the bottom of the diagram (no room below), we ENLARGE the
        canvas downward to reserve a dedicated band for it → never any overlap
        with the board (the old safeguard moved it up onto the board). cf
        _WATERMARK_*. Applies to exported AND copied PNGs, never to the on-screen preview.
        """
        renderer = QSvgRenderer(QByteArray(self._svg_str.encode("utf-8")))
        if not renderer.isValid():
            raise RuntimeError("SVG invalide")
        size = renderer.defaultSize()
        if size.isEmpty():
            size = QSize(1100, 800)
        # SVG render zone (top of the image): SVG coord → image = ×scale.
        region = QSize(int(size.width() * scale), int(size.height() * scale))

        wm = self._watermark_layout(renderer, region, scale)
        # Band added at the bottom if the watermark overflows the SVG zone.
        extra = 0
        if wm is not None:
            extra = max(0, int(math.ceil(wm["bottom"] + wm["margin"]))
                        - region.height())
        full = QSize(region.width(), region.height() + extra)

        image = QImage(full, QImage.Format.Format_ARGB32_Premultiplied)
        image.fill(Qt.GlobalColor.white)
        painter = QPainter(image)
        try:
            # SVG confined to the top zone (otherwise it would stretch over the band).
            renderer.render(painter, QRectF(0, 0, region.width(), region.height()))
            if wm is not None:
                self._paint_watermark(painter, wm)
        finally:
            painter.end()
        return image

    def _watermark_layout(self, renderer: QSvgRenderer, region: QSize,
                          scale: float) -> dict | None:
        """Geometry of the watermark (logo + URL) in final image coords.

        `region` = size of the SVG rendering. Anchored to the BOTTOM edge of
        the board (otherwise under all the content). Returns a dict ready to
        paint, or None if the logo cannot be found. `bottom` = base of the
        block, `margin` = margin under the block — used to size the band added
        by `_render_png_image`.
        """
        logo = QSvgRenderer(str(_LOGO_DIR / _WATERMARK_LOGO_SVG))
        if not logo.isValid():
            return None
        if renderer.elementExists(BOARD_INSTANCE_ID):
            b = renderer.boundsOnElement(BOARD_INSTANCE_ID)
            cx = b.center().x() * scale
            anchor_y = b.bottom() * scale         # bottom edge of the board
            avail_w = b.width() * scale
            ref_h = b.height() * scale
        else:
            cx = region.width() / 2
            anchor_y = float(region.height())     # under all the content
            avail_w = float(region.width())
            ref_h = float(region.height())

        # Logo in a box ~30 % × 21 % of the board (≈ 50 % of the old size),
        # ratio preserved.
        ds = logo.defaultSize()
        ratio = (ds.width() / ds.height()) if ds.height() else 1.0
        box_w, box_h = avail_w * 0.30, ref_h * 0.21
        logo_h = box_h
        logo_w = logo_h * ratio
        if logo_w > box_w:
            logo_w, logo_h = box_w, box_w / ratio

        font = QFont()
        font.setPixelSize(max(int(logo_h / 6), int(9 * scale)))
        font.setWeight(QFont.Weight.DemiBold)
        text_h = QFontMetricsF(font).height()
        gap = logo_h * 0.01                       # text ↔ logo spacing (tightened)
        gap_board = ref_h * 0.02                  # board ↔ watermark spacing
        # Vertical stacking: « Generated with » → logo → URL.
        top = anchor_y + gap_board
        tag_rect = QRectF(cx - avail_w / 2, top, avail_w, text_h)
        logo_rect = QRectF(cx - logo_w / 2, tag_rect.bottom() + gap, logo_w, logo_h)
        url_rect = QRectF(cx - avail_w / 2, logo_rect.bottom() + gap, avail_w, text_h)
        return {
            "logo": logo, "logo_rect": logo_rect, "url_rect": url_rect,
            "tag_rect": tag_rect, "font": font,
            "bottom": url_rect.bottom(), "margin": gap_board,
        }

    def _paint_watermark(self, painter: QPainter, wm: dict) -> None:
        """Paints the watermark computed by `_watermark_layout`: « Generated with »
        above the logo, URL below. The badge carries its own dark
        background; the texts (on the light zone) are in dark ink to stay
        legible."""
        painter.save()
        painter.setOpacity(_WATERMARK_OPACITY)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
        wm["logo"].render(painter, wm["logo_rect"])
        painter.setFont(wm["font"])
        painter.setPen(QColor("#161b26"))
        align = int(Qt.AlignmentFlag.AlignHCenter | Qt.AlignmentFlag.AlignTop)
        painter.drawText(wm["tag_rect"], align, _WATERMARK_TAGLINE)
        painter.drawText(wm["url_rect"], align, _WATERMARK_URL)
        painter.restore()

