def _build_qt_wire_path(points: list[tuple[float, float]],
                        radius: float) -> QPainterPath:
    """Manhattan QPainterPath with rounded corners (quad bezier).
    Replicates `_path_d_rounded` from layout/renderer.py but on the Qt side.
    """
    path = QPainterPath()
    n = len(points)
    if n < 2:
        return path
    path.moveTo(points[0][0], points[0][1])
    if n == 2:
        path.lineTo(points[1][0], points[1][1])
        return path
    for i in range(1, n - 1):
        p_prev = points[i - 1]
        p_curr = points[i]
        p_next = points[i + 1]
        dx_in = p_curr[0] - p_prev[0]
        dy_in = p_curr[1] - p_prev[1]
        dx_out = p_next[0] - p_curr[0]
        dy_out = p_next[1] - p_curr[1]
        seg_in = abs(dx_in) + abs(dy_in)
        seg_out = abs(dx_out) + abs(dy_out)
        r = min(radius, seg_in / 2, seg_out / 2)
        ux_in = 0.0 if dx_in == 0 else (1.0 if dx_in > 0 else -1.0)
        uy_in = 0.0 if dy_in == 0 else (1.0 if dy_in > 0 else -1.0)
        ux_out = 0.0 if dx_out == 0 else (1.0 if dx_out > 0 else -1.0)
        uy_out = 0.0 if dy_out == 0 else (1.0 if dy_out > 0 else -1.0)
        approach = (p_curr[0] - ux_in * r, p_curr[1] - uy_in * r)
        exit_pt = (p_curr[0] + ux_out * r, p_curr[1] + uy_out * r)
        path.lineTo(approach[0], approach[1])
        path.quadTo(p_curr[0], p_curr[1], exit_pt[0], exit_pt[1])
    path.lineTo(points[-1][0], points[-1][1])
    return path


