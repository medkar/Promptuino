class _ClickableComponentItem(QGraphicsSvgItem):
    """QGraphicsSvgItem that notifies the SchemaView on left click.

    Stores the component ref so the SchemaView knows which component
    was clicked. Used by SchemaView in multi-items mode for the
    components (off-BB and on-BB).
    """
    def __init__(self, ref: str, schema_view):
        super().__init__()
        self._ref = ref
        self._schema_view = schema_view
        self.setAcceptedMouseButtons(Qt.MouseButton.LeftButton)
        self.setAcceptHoverEvents(True)
        self.setCursor(Qt.CursorShape.PointingHandCursor)
        self._hover_outline = None

    def mousePressEvent(self, event):
        if event.button() == Qt.MouseButton.LeftButton:
            self._schema_view.on_component_clicked(self._ref)
            event.accept()
            return
        super().mousePressEvent(event)

    def hoverEnterEvent(self, event):
        from PyQt6.QtWidgets import QGraphicsRectItem
        from PyQt6.QtGui import QPen, QBrush
        from ..theme import theme_manager
        if self._hover_outline is None:
            br = self.sceneBoundingRect().adjusted(-2, -2, 2, 2)
            rect = QGraphicsRectItem(br)
            pen = QPen(QColor(theme_manager.current.accent))
            pen.setWidth(1)
            rect.setPen(pen)
            rect.setBrush(QBrush(Qt.BrushStyle.NoBrush))
            rect.setZValue(9)   # just below the glow (z=10)
            self._schema_view._gscene.addItem(rect)
            self._hover_outline = rect
        # Increment the hover counter to show the gear/info icon if this
        # component has one.
        self._schema_view._on_edit_hover_enter(self._ref)
        super().hoverEnterEvent(event)

    def hoverLeaveEvent(self, event):
        if self._hover_outline is not None:
            self._schema_view._gscene.removeItem(self._hover_outline)
            self._hover_outline = None
        # Decrement the hover counter. The gear/info icon only disappears
        # if the counter drops back to 0 AND the ref is not selected.
        self._schema_view._on_edit_hover_leave(self._ref)
        super().hoverLeaveEvent(event)


# Overlay action icons (gear / attention / help "i"): LOGICAL size of the
# disc in scene units, and supersampling factor. The pixmaps are rendered at
# _ICON_SS x the logical size and the items scaled back by 1/_ICON_SS with a
# smooth transformation -> the icons stay crisp when the view zooms in
# (up to ~400%), instead of stretching a 22px bitmap.
_ICON_PIX_SIZE = 22
_ICON_SS = 4


def _init_overlay_icon_item(item: QGraphicsPixmapItem) -> None:
    """Shared setup of the supersampled overlay icons (cf. _ICON_SS)."""
    item.setScale(1.0 / _ICON_SS)
    item.setTransformationMode(Qt.TransformationMode.SmoothTransformation)


