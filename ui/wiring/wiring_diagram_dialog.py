# Object name of the "the illustration is missing" placeholder shown by the
# L298N / A4988 help modals when their SVG asset cannot be loaded. Named
# rather than styled inline so `_style_choice_dialog` can theme it: the
# literal light-grey hex it used to hard-code stayed light-on-light in the
# dark theme, i.e. the fallback meant to explain a missing asset was itself
# unreadable exactly when it appeared.
ASSET_PLACEHOLDER_NAME = "assetPlaceholder"


def _style_choice_dialog(dialog: QDialog, button_box: QDialogButtonBox) -> None:
    """Applies the centralized style to the controls of a small info/choice
    modal (Level 3 sub-dialogs) and follows the theme change.

    - QRadioButton / QCheckBox -> radio_checkbox_qss (green on hover + check).
    - QDialogButtonBox Ok button -> PRIMARY (filled, green on hover).
    - Cancel button -> SECONDARY (outlined, green on hover).
    - QLabel#assetPlaceholder -> themed "missing illustration" placeholder.
    The radio_checkbox_qss QSS set on the dialog targets ONLY radios/checkboxes:
    it touches neither the QLabel (pedagogical text) nor the modal's background.
    The buttons are styled individually (priority over the parent QSS).
    """
    sb = QDialogButtonBox.StandardButton

    def _apply(c: ColorScheme):
        # The placeholder rule is scoped by object name, so it reaches only
        # that one label and leaves every other QLabel of the modal alone.
        dialog.setStyleSheet(
            radio_checkbox_qss(c)
            + f"""
            QLabel#{ASSET_PLACEHOLDER_NAME} {{
                background: {c.surface};
                border: 1px dashed {c.border};
                color: {c.text_secondary};
                border-radius: 6px;
                padding: 8px;
            }}
            """
        )
        ok = button_box.button(sb.Ok)
        if ok is not None:
            ok.setCursor(Qt.CursorShape.PointingHandCursor)
            ok.setStyleSheet(primary_button_qss(c))
        cancel = button_box.button(sb.Cancel)
        if cancel is not None:
            cancel.setCursor(Qt.CursorShape.PointingHandCursor)
            cancel.setStyleSheet(secondary_button_qss(c))

    _apply(theme_manager.current)
    # Follows the theme as long as the modal lives, then disconnects cleanly
    # at its closing (lambda slot not bound to the dialog -> Qt does not
    # auto-disconnect it, we do it explicitly on `finished` to avoid a
    # dangling slot that would touch destroyed widgets).
    slot = lambda c: _apply(c)
    theme_manager.changed.connect(slot)

    def _disconnect(*_):
        try:
            theme_manager.changed.disconnect(slot)
        except (TypeError, RuntimeError):
            pass

    dialog.finished.connect(_disconnect)


