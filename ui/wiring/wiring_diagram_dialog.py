    def _show_warning_info(self, ref: str) -> None:
        """Repli du clic sur la puce d'attention : montre l'avertissement déjà
        émis pour ce composant.

        `_on_info_clicked` ne connaissait que `unrecognized`, `unwired_pins` et
        trois types de drivers. Les deux autres filets d'honnêteté du détecteur
        — `presumed_wiring` et `presumed_analog` — portent bien la puce (cf.
        `_compute_info_refs`) mais n'avaient AUCUNE branche : curseur « main »,
        clic avalé, rien affiché (QA L1, 2026-08-10). Un repli générique vaut
        mieux qu'une branche de plus, parce qu'il couvrira aussi le prochain
        filet ajouté.

        Le texte réutilisé est celui du warning, comme pour l'infobulle : en
        écrire un second serait de la prose neuve à maintenir en double.
        """
        if self._netlist is None:
            return
        from PyQt6.QtWidgets import QMessageBox
        from .instructions import _render_warning_message
        lang = lang_manager.lang
        # MEME PRIORITE QU'A L'INFOBULLE (`_compute_info_tooltips`) : les
        # codes de confrontation passent devant la regle « premier warning
        # par ref », qui depend de l'ordre d'emission de TOUTE la netlist et
        # pas seulement du notre. Sans ca, survol et clic se CONTREDISENT sur
        # le meme composant -- mesure de la revue finale du #45 sur deux
        # fiches declarees : le survol dit la contradiction, le clic
        # ressortait « Pin  utilisee par plusieurs composants : U1, U1... »,
        # le `pin_double_use` calcule sur les nets VIDES des placeholders,
        # avant que la declaration ne s'applique.
        priority = _confrontation_addressees(
            getattr(self._netlist, "warnings", []),
            self._CONFRONTATION_CODES).get(ref)
        codes = self._CONFRONTATION_CODES
        ordered = [w for w in getattr(self._netlist, "warnings", [])
                   if getattr(w, "code", None) not in codes]
        if priority is not None:
            ordered.insert(0, priority)
        for w in ordered:
            if ref not in (getattr(w, "refs", None) or []):
                continue
            txt = _render_warning_message(w, lang)
            if not txt:
                continue
            QMessageBox.information(
                self,
                _t(_INFO_TITLE_BY_CODE.get(w.code, "info_title_generic"), lang),
                # Les gabarits portent du gras markdown, qu'une QMessageBox
                # afficherait tel quel (même raison que dans l'infobulle).
                txt.replace("**", ""),
            )
            return

    def _on_gear_clicked(self, ref: str) -> None:
        """Gear click: opens a dropdown menu listing the component's
        actions (Edit / implicit actions / "This is not the right
        component"). The amber info icon stays separate."""
        if self._netlist is None:
            return
        target = next(
            (c for c in self._netlist.components if c.ref == ref),
            None,
        )
        if target is None:
            return
        from . import implicit_actions as _ia
        from .component_menu import menu_entries
        actions = _ia.available_actions(target, self._netlist)
        base_editable = False
        if self._editable_refs_fn is not None:
            try:
                base_editable = ref in self._editable_refs_fn(self._netlist)
            except Exception:
                base_editable = False
        editable = gear_menu_editable(target, base_editable)
        lang = self._instructions_lang()
        labels = {
            "edit": _t("menu_edit_component", lang),
            "wrong_component": _t("menu_wrong_component", lang),
        }
        # Anti-"replay" guard. When clicking outside a QMenu to close it,
        # Windows re-emits this click to the widget under the cursor
        # (qt_replay_popup_mouse_event). If the component is selected, its
        # gear stays permanently visible -> the replayed click lands back on
        # the gear and would reopen the menu at the clicked position ("it
        # stays and moves to where I clicked"). So we ignore any reopening
        # happening just after the previous menu closed (the replay is nearly
        # instantaneous; 300ms is well below any intended reopening).
        import time
        if time.monotonic() - getattr(self, "_last_gear_menu_close", 0.0) < 0.3:
            return
        entries = menu_entries(editable=editable, actions=actions, labels=labels)
        menu = QMenu(self)
        for i, entry in enumerate(entries):
            if entry.kind == "wrong_component" and i > 0:
                menu.addSeparator()
            act = menu.addAction(entry.label)
            if entry.kind == "edit":
                act.triggered.connect(
                    lambda checked=False, r=ref: self._edit_component(r)
                )
            elif entry.kind == "implicit":
                act.triggered.connect(
                    lambda checked=False, r=ref, a=entry.action_id:
                    self._run_implicit_action(r, a)
                )
            elif entry.kind == "wrong_component":
                act.triggered.connect(
                    lambda checked=False, r=ref: self._on_wrong_component_entry(r)
                )
        menu.exec(QCursor.pos())
        self._last_gear_menu_close = time.monotonic()

    def _run_implicit_action(self, ref: str, action_id: str) -> None:
        """Executes a given Level 3 implicit action (dispatch the
        dedicated modal, compare the value, apply via the callback,
        regenerate). Extracted from the old _on_gear_clicked, but targets
        a precise action_id (the menu can list several)."""
        if self._netlist is None or self._toggle_implicit_action_fn is None:
            return
        target = next(
            (c for c in self._netlist.components if c.ref == ref),
            None,
        )
        if target is None:
            return
        from . import implicit_actions as _ia
        act = next(
            (a for a in _ia.available_actions(target, self._netlist)
             if a.id == action_id),
            None,
        )
        if act is None:
            return
        if act.id == "servo_external_power":
            dlg = _ServoExternalPowerDialog(
                self, ref=ref, is_external=act.is_active,
            )
        elif act.id == "led_series_value":
            dlg = _LedSeriesValueDialog(
                self, ref=ref, current_value=str(act.value or "220"),
            )
        elif act.id == "btn_pullup_external":
            dlg = _BtnPullupDialog(
                self, ref=ref, is_external=act.is_active,
            )
        elif act.id == "dht_data_pullup":
            dlg = _DhtPullupDialog(
                self, ref=ref, has_pullup=act.is_active,
            )
        elif act.id == "buzzer_series_value":
            dlg = _BuzzerSeriesValueDialog(
                self, ref=ref, current_value=str(act.value or "100"),
            )
        elif act.id == "ds18b20_pullup_value":
            dlg = _Ds18b20PullupDialog(
                self, ref=ref, current_value=str(act.value or "4.7k"),
            )
        elif act.id == "a4988_microstepping":
            dlg = _A4988MicrosteppingDialog(
                self, ref=ref, current_value=str(act.value or "full"),
            )
        else:
            return
        if dlg.exec() != QDialog.DialogCode.Accepted:
            return
        chosen = dlg.chosen_value
        if act.choices is None:
            if bool(chosen) == bool(act.is_active):
                return
            ok = self._toggle_implicit_action_fn(ref, act.id, self._netlist)
        else:
            if str(chosen) == str(act.value):
                return
            ok = self._toggle_implicit_action_fn(
                ref, act.id, self._netlist, value=chosen,
            )
        if ok:
            self._regenerate()

    def _on_wrong_component_entry(self, ref: str) -> None:
        """Menu entry "Ask the chat for advice". Confirms first (pop-up
        explaining that the question will be asked in the chat), then
        delegates to the studio callback that opens the chat. Falls back to
        the technical modal if the callback did not handle it (degraded case).

        The popup offers a "Don't ask me again" checkbox (persisted in
        session.json): once checked, the following clicks open the chat
        directly without confirmation."""
        lang = self._instructions_lang()
        if not session.skip_wrong_component_confirm:
            box = QMessageBox(self)
            box.setIcon(QMessageBox.Icon.Information)
            box.setWindowTitle(_t("menu_wrong_component", lang))
            box.setText(_t("wrong_component_confirm_body", lang))
            dont_ask = QCheckBox(_t("wrong_component_dont_ask", lang))
            box.setCheckBox(dont_ask)
            ok_btn = box.addButton(
                _t("wrong_component_confirm_ok", lang),
                QMessageBox.ButtonRole.AcceptRole,
            )
            box.addButton(
                _t("wrong_component_confirm_cancel", lang),
                QMessageBox.ButtonRole.RejectRole,
            )
            box.exec()
            if box.clickedButton() is not ok_btn:
                # Cancel: we do NOT persist the checkbox (ambiguous intent).
                return
            if dont_ask.isChecked():
                session.skip_wrong_component_confirm = True
        handled = False
        if self._wrong_component_fn is not None and self._netlist is not None:
            try:
                handled = bool(self._wrong_component_fn(ref, self._netlist))
            except Exception:
                handled = False
        if not handled:
            self._edit_component(ref)

    def _edit_component(self, ref: str) -> None:
        """Level 2 (accessible via the gear menu): re-run the ambiguity
        modal scoped to this component only. If the user validates, the
        new resolution is saved (StudioView calls save_project); if they
        cancel we keep the old resolution (resolve_fn returns None, we do
        nothing).

        If `ref` points to a driver (l298n, l293d, etc.), we redirect to
        the associated motor via `_paired_motor`: the resolution is saved
        under the motor's key, not the driver's (the driver is added by
        inference, not detected in the user code).
        """
        if self._resolve_fn is None:
            return
        effective_ref = ref
        if self._netlist is not None:
            c = next(
                (x for x in self._netlist.components if x.ref == ref),
                None,
            )
            if c is not None:
                paired = c.attributes.get("_paired_motor")
                if paired:
                    # `_paired_motor` can be "M1" or "M1,M2" (dual
                    # H-bridge). We take the 1st: the modal will
                    # automatically group the motors of a same fn.
                    effective_ref = str(paired).split(",")[0].strip()
        netlist = self._resolve_fn(
            self._code, self._board_id, self._prompt, self._context,
            self._prompts_by_fn, force_remodal=True,
            scoped_to_ref=effective_ref,
        )
        if netlist is None:
            return   # modal cancelled
        self._netlist = netlist
        self._regenerate()

    def _on_zoom_changed(self, scale: float) -> None:
        """Updates the toolbar's percentage field with the current value.
        Called on every +/- / fit / wheelzoom / set_zoom.

        If the user is editing (focus in the field), we don't override
        their current text -- their editingFinished will handle it. Same
        if we are in the middle of dispatching a previous editingFinished
        (re-entry guard)."""
        if self._zoom_edit_busy:
            return
        if self._zoom_edit.hasFocus():
            return
        text = _fmt_pct(scale)
        if self._zoom_edit.text() != text:
            self._zoom_edit.setText(text)

    def _on_zoom_edit_finished(self) -> None:
        """Parses the typed text (accepted formats: '100', '100%', '100 %')
        and applies the zoom. On parsing failure, restores the current
        value. The clamp [_ZOOM_MIN, _ZOOM_MAX] is applied by
        SchemaView.set_zoom().

        editingFinished can re-trigger within the handler (on focusOut
        induced by other widgets taking the focus). The `_zoom_edit_busy`
        flag avoids the re-entry that could revert the just-applied
        value."""
        if self._zoom_edit_busy:
            return
        self._zoom_edit_busy = True
        try:
            raw = self._zoom_edit.text().strip().rstrip("%").strip()
            pct = None
            try:
                pct = float(raw.replace(",", "."))
            except ValueError:
                pass
            if pct is None:
                self._zoom_edit.setText(
                    _fmt_pct(self._schema_view._current_scale()))
                return
            self._schema_view.set_zoom(pct / 100.0)
            self._zoom_edit.setText(
                _fmt_pct(self._schema_view._current_scale()))
        finally:
            self._zoom_edit_busy = False

