def _confrontation_addressees(warnings, codes) -> dict:
    """{ref destinataire : 1er warning de confrontation qui LUI parle}.

    ⚠️ SEULE LA PREMIÈRE REF EST DESTINATAIRE, et ce n'est pas un détail de
    forme. `declared_pin_already_claimed` porte `refs=[fiche, adverse]`, et
    son message est rédigé du POINT DE VUE DE LA FICHE : « La fiche X câble
    D9, déjà utilisée par un autre composant du schéma (SV1) ». Donné à
    l'adverse, ce texte se lit à l'envers — mesuré en revue finale du #45 :
    survoler un servo détecté par `Servo.h` (donc avec CERTITUDE, et sans la
    moindre pastille avant ce ticket) affichait la phrase de la fiche, en se
    nommant lui-même comme le coupable.
    `refs` garde ses DEUX entrées : le lien vers l'adverse a sa valeur
    ailleurs (panneau d'instructions, surlignage). C'est la couche
    d'affichage de la pastille qui se restreint, pas le warning.

    Le défaut n'a été visible qu'à l'exécution parce que le test et la QA
    prenaient tous deux une LED comme adverse : la LED porte déjà
    `led_series_resistor`, qui gagnait le premier-warning-par-ref et masquait
    le problème. L'adverse sans warning antérieur (servo, bouton, écran) est
    le cas COURANT.
    """
    out: dict = {}
    for w in (warnings or []):
        if getattr(w, "code", None) not in codes:
            continue
        refs = getattr(w, "refs", None) or []
        if not refs:
            continue
        out.setdefault(refs[0], w)
    return out


# Longueur de ligne de l'infobulle, en CARACTÈRES. Sans repli, Qt étale un
# avertissement long sur UNE ligne large de plus de 2000 px (QA E2,
# 2026-08-08). Le repli est explicite parce qu'AUCUNE contrainte de largeur
# déclarative ne fonctionne : mesuré sur `QToolTip.font()`, `<table width>`,
# `<td width>`, `<div style="width">` et `<p style="width">` laissent tous la
# ligne à 2330 px. 72 caractères donnent ~410 px sur 4 lignes.
_TOOLTIP_WRAP_CHARS = 72


def _tooltip_html(title: str, body: str) -> str:
    """Infobulle : titre en gras sur la 1re ligne, puis le texte replié.

    On replie le texte BRUT avant de l'échapper : `&` devient `&amp;`, cinq
    caractères pour un seul affiché, ce qui fausserait la coupure. `Qt.escape`
    n'existe pas côté Python, d'où l'échappement à la main — sans lui, un
    libellé contenant « & » ou « < » casserait le rendu.
    """
    import textwrap

    def esc(s: str) -> str:
        return (s.replace("&", "&amp;").replace("<", "&lt;")
                 .replace(">", "&gt;"))

    lines = textwrap.wrap(body or "", _TOOLTIP_WRAP_CHARS) or [""]
    return f"<b>{esc(title)}</b><br>" + "<br>".join(esc(l) for l in lines)


def gear_menu_editable(target, base_editable: bool) -> bool:
    """Final editability of the gear menu for `target`.

    `base_editable`: True if the component has a saved wiring resolution
    (cf `_editable_refs_fn`, Level 2 interactive schema). Even when False,
    the component can still be self-correctable from its own type/state:
    - `is_replaceable`: known catalog type with a proposable category.
    - `is_uncertain_component`: the detector produced it "faute de mieux"
      (unrecognized include / presumed I2C wiring) -- without this, the
      banner "clique sur l'engrenage pour corriger" would lie precisely
      when the app most likely got it wrong (review 2026-07-29).
    - `is_user_declared`: the user described this component themselves; it
      belongs to no electrical category (`is_replaceable` is False for it)
      and carries none of the "uncertain" attributes anymore (dropped by
      the declaration), so without this it would be a dead end the moment
      it's declared (review 2026-07-30 #1).

    Extracted as a pure module-level function (rather than inlined in
    `_on_gear_clicked`) so removing any one of the three from this
    predicate is caught by a headless test instead of only surfacing as a
    silently-muted gear in the running app.
    """
    from .replacement_ui import is_replaceable, is_uncertain_component, is_user_declared
    return (base_editable or is_replaceable(target.type)
            or is_uncertain_component(target)
            or is_user_declared(target))


