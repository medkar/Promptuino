class _GearActionItem(QGraphicsPixmapItem):
    """Level 3 gear: component menu (options + editing). Same
    visibility mechanics as the info icon (hover counter + 80ms
    deferral for the component->icon mouse transition).

    Since the pencil->gear merge (Task 5), only the Active state
    (active=True) is used: the gear is always shown on non-resistance
    components and opens a menu. The inactive infrastructure (greyed,
    opacity 0.45) is kept for future evolution but is no longer
    instantiated in practice.
    """
    def __init__(self, ref: str, schema_view, pixmap: QPixmap,
                  *, active: bool = True, tooltip: str = ""):
        super().__init__(pixmap)
        _init_overlay_icon_item(self)
        self._ref = ref
        self._schema_view = schema_view
        self._active = active
        self.setAcceptedMouseButtons(Qt.MouseButton.LeftButton)
        self.setAcceptHoverEvents(True)
        if active:
            self.setCursor(Qt.CursorShape.PointingHandCursor)
        else:
            self.setCursor(Qt.CursorShape.ArrowCursor)
            self.setOpacity(0.45)
        if tooltip:
            self.setToolTip(tooltip)
        self.setZValue(11)
        self.setVisible(False)

    def mousePressEvent(self, event):
        if event.button() == Qt.MouseButton.LeftButton and self._active:
            fn = self._schema_view._gear_click_fn
            if fn is not None:
                # Defer opening the menu by one loop iteration. Calling
                # menu.exec() directly here would start a nested event loop
                # WHILE the scene still holds the press's mouse grab (the
                # release is swallowed by the menu): the outside-click that
                # closes the menu is then re-propagated to the scene and
                # reopens the menu at the cursor position. The singleShot(0)
                # lets the press finish (grab released) before opening;
                # QCursor.pos() is unchanged at 0 ms so the menu always
                # appears on the gear.
                QTimer.singleShot(0, lambda r=self._ref: fn(r))
            event.accept()
            return
        if event.button() == Qt.MouseButton.LeftButton:
            # Inactive: accept the event so it does not deselect the
            # current component.
            event.accept()
            return
        super().mousePressEvent(event)

    def hoverEnterEvent(self, event):
        self._schema_view._on_edit_hover_enter(self._ref)
        super().hoverEnterEvent(event)

    def hoverLeaveEvent(self, event):
        self._schema_view._on_edit_hover_leave(self._ref)
        super().hoverLeaveEvent(event)


